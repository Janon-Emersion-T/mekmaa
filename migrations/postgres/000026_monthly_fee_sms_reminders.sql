CREATE TABLE monthly_fee_sms_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    admission_id BIGINT NOT NULL
        REFERENCES admissions(id) ON DELETE RESTRICT,

    reminder_month TEXT NOT NULL,

    guardian_phone TEXT NOT NULL,

    outstanding_amount NUMERIC(14,2) NOT NULL
        CHECK (outstanding_amount > 0),

    message TEXT NOT NULL,

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending',
            'sending',
            'sent',
            'failed',
            'uncertain'
        )),

    attempt_count INTEGER NOT NULL DEFAULT 0
        CHECK (attempt_count >= 0),

    last_error TEXT NOT NULL DEFAULT '',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempted_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,

    CONSTRAINT monthly_fee_sms_reminders_unique
        UNIQUE (admission_id, reminder_month)
);

CREATE INDEX idx_monthly_fee_sms_reminders_status
    ON monthly_fee_sms_reminders(status, reminder_month);
