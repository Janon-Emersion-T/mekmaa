-- Preserve every booking receivables archive and restore action.
-- RESTRICT prevents deletion of bookings with archive audit history.
CREATE TABLE booking_receivables_archive_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL
        REFERENCES space_schedules(id) ON DELETE RESTRICT,
    action TEXT NOT NULL CHECK (action IN ('archive', 'restore')),
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    reason TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_booking_receivables_archive_events_schedule
    ON booking_receivables_archive_events (schedule_id, created_at DESC, id DESC);
